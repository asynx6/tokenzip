function text(str, x0, y0, c, scale = 2) {
  let x = x0;
  for (const ch of str.toUpperCase()) {
    const g = G[ch] || G[' '];
    const rows = g.split(' ');
    rows.forEach((row, ry) => {
      [...row].forEach((bit, rx) => {
        if (bit === '1') rect(x + rx * scale, y0 + ry * scale, scale, scale, c);
      });
    });
    x += 6 * scale;
  }
}

